// The Worker's entry point (wrangler.jsonc "main"). Everything goes to the site that OpenNext builds into
// .open-next/worker.js, except the films in public/ and the admin's uploads at /cms/.
//
// Cloudflare serves public/ as static assets, and static assets answer a Range request with the whole file and 200.
// Safari (and every browser on iPhone) only plays a film whose server answers ranges with 206. So requests for
// films are routed here first (assets.run_worker_first in wrangler.jsonc) and answered with the requested bytes.
// The admin's uploads live in R2 and are answered here too, at /cms/<path> (lib/cms/r2-files.ts), so films and
// images skip the site's own code and keep their length.
//
// A static asset reaches the Worker without its size, so `npm run cf:build` lists the size of every film it ships
// in .open-next/film-sizes.json (scripts/film-sizes.mjs).

import { serveUpload } from '../lib/cms/r2-files.ts';
import { byteRange } from '../lib/http-range.ts';
// Both generated by `npm run cf:build`.
import sizes from '../.open-next/film-sizes.json';
import handler from '../.open-next/worker.js';

export { BucketCachePurge, DOQueueHandler, DOShardedTagCache } from '../.open-next/worker.js';

const FILM = /\.(mp4|webm|mov|m4v)$/i;

/** The bytes from start to end (inclusive) of a stream, reading no further than end. */
function slice(body, start, end) {
  const reader = body.getReader();
  let position = 0;
  return new ReadableStream({
    async pull(controller) {
      for (;;) {
        const { done, value } = await reader.read();
        if (done) {
          controller.close();
          return;
        }
        const from = position;
        position += value.byteLength;
        if (position <= start) continue;
        controller.enqueue(value.subarray(Math.max(0, start - from), Math.min(value.byteLength, end + 1 - from)));
        if (position > end) {
          controller.close();
          reader.cancel().catch(() => {});
        }
        return;
      }
    },
    cancel(reason) {
      return reader.cancel(reason);
    },
  });
}

/** A film from public/, with ranges answered; null when there is no such file, so the site's 404 page shows. */
async function serveFilm(request, env, size) {
  const headers = new Headers(request.headers);
  const rangeHeader = headers.get('range');
  headers.delete('range');
  headers.delete('if-range');
  const asset = await env.ASSETS.fetch(new Request(request.url, { method: request.method, headers }));
  if (asset.status === 404) return null;

  const out = new Headers(asset.headers);
  out.set('accept-ranges', 'bytes');
  if (asset.status !== 200) return new Response(asset.body, { status: asset.status, headers: out });

  const range = byteRange(rangeHeader, size);
  if (range === null) {
    out.set('content-length', String(size));
    return new Response(asset.body, { status: 200, headers: out });
  }

  if (range === 'unsatisfiable') {
    await asset.body?.cancel();
    out.set('content-range', `bytes */${size}`);
    out.delete('content-length');
    return new Response(null, { status: 416, headers: out });
  }

  const length = range.end - range.start + 1;
  out.set('content-range', `bytes ${range.start}-${range.end}/${size}`);
  out.set('content-length', String(length));
  if (request.method === 'HEAD' || !asset.body) {
    await asset.body?.cancel();
    return new Response(null, { status: 206, headers: out });
  }
  // The whole file from the start ("bytes=0-", what a browser asks for first) passes straight through.
  if (range.start === 0 && range.end === size - 1) return new Response(asset.body, { status: 206, headers: out });

  const { readable, writable } = new FixedLengthStream(length);
  slice(asset.body, range.start, range.end).pipeTo(writable).catch(() => {});
  return new Response(readable, { status: 206, headers: out });
}

export default {
  async fetch(request, env, ctx) {
    const { pathname } = new URL(request.url);
    const read = request.method === 'GET' || request.method === 'HEAD';
    if (read && pathname.startsWith('/cms/') && env.CMS_UPLOADS) {
      return serveUpload(env.CMS_UPLOADS, pathname.slice('/cms/'.length), request);
    }
    if (read && FILM.test(pathname)) {
      let path = pathname;
      try {
        path = decodeURIComponent(pathname);
      } catch {
        // A malformed address is looked up as it is, and simply not found.
      }
      const size = sizes[path];
      if (typeof size === 'number' && size > 0) {
        const film = await serveFilm(request, env, size);
        if (film) return film;
      }
    }
    return handler.fetch(request, env, ctx);
  },
};
